// Default player names per language. Used to translate auto-generated casilla
// names (home/away/Player N) when switching language, without touching custom
// names the user typed.
const DEFAULT_PLAYER_NAMES = {
  es: { home: "Casa", away: "Visitante", player: (n: number) => `Jugador ${n}` },
  en: { home: "House", away: "Visitors", player: (n: number) => `Player ${n}` },
  pt: { home: "Casa", away: "Visitantes", player: (n: number) => `Jogador ${n}` },
  fr: { home: "Maison", away: "Visiteurs", player: (n: number) => `Joueur ${n}` },
  it: { home: "Casa", away: "Visitatori", player: (n: number) => `Giocatore ${n}` },
} as const;

export function translateTeamName(name: string, lang: Lang): string {
  return translatePlayerName(name, lang);
}

export function translatePlayerName(name: string, lang: Lang): string {
  const trimmed = name.trim();
  if (trimmed === "Casa" || trimmed === "House") return DEFAULT_PLAYER_NAMES[lang].home;
  if (trimmed === "Visitante" || trimmed === "Visitors" || trimmed === "Visitantes" || trimmed === "Visiteurs" || trimmed === "Visitatori") {
    return DEFAULT_PLAYER_NAMES[lang].away;
  }
  const match = trimmed.match(/^(?:Jugador|Player|Jogador|Joueur|Giocatore)\s+(\d+)$/);
  if (match) {
    const num = parseInt(match[1], 10);
    return DEFAULT_PLAYER_NAMES[lang].player(num);
  }
  return trimmed;
}
